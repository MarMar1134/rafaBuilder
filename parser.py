import argparse
from version import __version__ as ver

def defineParser():
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("-v", "--verbose", action="store_true", dest="verbose",
                         help="runs the specified command with extra information while working")
    common.add_argument("-q", "--quiet", action="store_true", dest="quiet",
                        help="disables any non-error message")
    common.add_argument("-d", "--debug", action="store_true", dest="debug",
                        help="enables debug mode, showing additional messages about the compilation process")

    parser = argparse.ArgumentParser(prog="rb", parents=[common], description="RafaBuilder base command")
    parser.add_argument("-V", "--version", action="version", version=f"%(prog)s {ver}")

    commands = parser.add_subparsers(title="commands", dest="cmd")

    commands.add_parser(name="check", parents=[common], help="Scans the working directory searching for 'attributes.rafa'",
                        description="This command scans the current working directory for a file named 'attributes.rafa'. If missing, it exits with an error code.")
    commands.add_parser(name="compile", parents=[common], help="Creates .o files and stores them under '/build'",
                        description="This command grabs all the files under the source directory specified on 'attributes.rafa' and generates an .o file for each one of them."
                        " Every .o file is stored under the '/build' directory, created, if doesn't exists, under the working directory.")
    commands.add_parser(name="link", parents=[common], help="links the .o files found on '/build'",
                        description="This command searches for every .o file generated by 'compile' and links them all, creating an executable under '/bin', on the working directory." \
                        " If there are no .o files under '/build', throws an error message and ends the execution.")
    commands.add_parser(name="make", parents=[common], help="creates .o files and links them. The executable is stored under '/bin'",
                        description="This command searches for .o files under '/build', links them and puts the executable under '/bin'."
                        " If no .o files are found, searches for cpp and/or .c files and makes a full compilation-linking process. The executable is stored under '/bin', on the working directory.")
    commands.add_parser(name="run", parents=[common], help="Searches for .o files under '/build' and tries to create an executable. "
                        " If no .o files are found, compiles src files, links them and then runs the executable.",
                        description="This command searches for .o files under '/build', links them and puts the executable under '/bin', then it runs the executable."
                        " If no .o files are found, searches for .cpp and/or .c files and makes a full compilation-linking process. If succesfull, runs the executable.")
    commands.add_parser(name="clean", parents=[common], help="Removes '/build' and '/bin' from the working directory",
                        description="This command deletes '/build' and '/bin' directories with all its contents. If some of the directories doesn't exists, skips them and continues the search.")

    return parser

def quietModeEnabled(parser):
    return parser.quietMode